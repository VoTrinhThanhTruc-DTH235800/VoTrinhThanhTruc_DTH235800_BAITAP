a = float(input("Nhap a: "));
b = float(input("Nhap b: "));
c = str(input("Nhap dau: "));

if (c == "+" ):
    print("{a} + {b} = ", a+b);
elif (c == "-"):
    print("{a} - {b} = ", a-b);
elif (c == "*"):
    print("{a} * {b} = ", a*b);
elif (c == "/"):
    print("{a} / {b} = ", a/b);


    



